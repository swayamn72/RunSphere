/** Shapes the app's icon component can draw. Anything else is refused, not dropped. */
const SHAPES = new Set(['path', 'circle', 'rect', 'line']);

const shapesIn = (name, svg) => {
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  return [...inner.matchAll(/<([a-z]+)\s([^>]*?)\/>/g)].map(([, tag, attributes]) => {
    if (!SHAPES.has(tag)) throw new Error(`${name}.svg uses <${tag}>, which Icon can't draw.`);
    const pairs = [...attributes.matchAll(/([a-zA-Z0-9-]+)="([^"]*)"/g)].map(
      ([, key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`
    );
    return `{ tag: ${JSON.stringify(tag)}, attributes: { ${pairs.join(', ')} } }`;
  });
};

/** `[name, svgSource][]` to the TypeScript module the app imports. */
export const renderIconModule = (files) =>
  [
    '// Generated by scripts/generate-icons.mjs from assets/icons/lucide. Do not edit.',
    '// Icons: Lucide (ISC), see assets/icons/lucide/LICENSE.',
    '',
    'export interface IconShape {',
    "  tag: 'path' | 'circle' | 'rect' | 'line';",
    '  attributes: Readonly<Record<string, string>>;',
    '}',
    '',
    'export const lucideIcons = {',
    files
      .map(
        ([name, svg]) =>
          `  ${JSON.stringify(name)}: [\n    ${shapesIn(name, svg).join(',\n    ')}\n  ]`
      )
      .join(',\n'),
    '} satisfies Record<string, readonly IconShape[]>;',
    '',
    'export type IconName = keyof typeof lucideIcons;',
    ''
  ].join('\n');
